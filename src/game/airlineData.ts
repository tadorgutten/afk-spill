export type ContinentId = 'na' | 'sa' | 'eu' | 'as' | 'af' | 'oc' | 'me';
export type PlaneId = 'small' | 'medium' | 'large' | 'xlarge';

export interface Airport {
  code: string;
  city: string;
  /** Landkode (flagg i public/airline/flags). */
  cc: string;
}
export interface HubDef {
  code: string;
  name: string;
  /** Leiepris. */
  price: number;
}
export interface FlightDef {
  id: string;
  cont: ContinentId;
  from: string;
  to: string;
  /** Hvilken hub (nr. i rekkefølgen) flyvningen går fra – den må være leid. */
  hub: number;
  intl: boolean;
  /** Flytid i minutter (bare til visning). */
  minutes: number;
  plane: PlaneId;
  /** Hvor mange fly av typen som trengs. */
  count: number;
  /** Inntekt per time når flyvningen er i gang. */
  income: number;
  /** Pris for å lansere. */
  cost: number;
}
export interface ContinentDef {
  id: ContinentId;
  name: string;
  license: number;
  hubs: HubDef[];
  flights: FlightDef[];
}
export interface PlaneDef {
  id: PlaneId;
  name: string;
  size: string;
  price: number;
}

